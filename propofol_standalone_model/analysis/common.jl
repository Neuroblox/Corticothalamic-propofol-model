# Shared helpers for the analysis scripts: load the standalone models, set the propofol dose,
# solve a trial and compute the simulated multi-unit activity (MUA) of a cortical region.
#
# The six model files share their equations and initial state and differ only in their parameter
# values (`p0`), so only one file is compiled; the parameter values of the others are read from
# their `const p0 = ...` line.

using OrdinaryDiffEqVerner
using SciMLBase: ReturnCode
using Statistics

const MODEL_DIR = normpath(joinpath(@__DIR__, "..", "models"))
const TRIALS = (:LOGO, :LOGR, :LRGR)
const TONE_STARTS = (100.0, 250.0, 400.0, 550.0, 700.0)   # ms
const TONE_WIDTH = 50.0                                   # ms
const P_ANESTHETIC = 2.5   # dose factor of the `anesthetized` files (awake files: 1.0)

# Compile the equations once, from one of the files.
include(joinpath(MODEL_DIR, "LRGR_awake.jl"))
const MODEL = LRGR_awake

"Read the vector following `const <name> = ` in a model file, without compiling the file."
function read_const_vector(path, name)
    prefix = "const $name = "
    for line in eachline(path)
        startswith(line, prefix) || continue
        body = strip(line[length(prefix)+1:end])
        body = body[findfirst('[', body)+1:findlast(']', body)-1]
        return name == "p0" ? parse.(Float64, split(body, ',')) :
                              Symbol.(lstrip.(strip.(split(body, ',')), ':'))
    end
    error("no `$prefix` line in $path")
end

"""
    parameters(trial, condition)

The parameter vector of the model file `<trial>_<condition>.jl` (condition `:awake` or
`:anesthetized`), checked to have the same parameter names as the compiled model.
"""
function parameters(trial, condition)
    path = joinpath(MODEL_DIR, "$(trial)_$(condition).jl")
    read_const_vector(path, "param_names") == MODEL.param_names ||
        error("$path has different parameter names from the compiled model")
    read_const_vector(path, "p0")
end

"""
    parameters_at_dose(trial, P)

The parameter vector of `trial` at propofol dose factor `P` (1 = awake, 2.5 = anesthetic).

In the model every dose-dependent parameter is linear in `P`: the conductance and decay time
constant of every GABA-A synapse and the weights of the tonic GPi inhibition scale as `P`, and the
weight of the ascending drive of the reticular nuclei is `2.5 - P`. The parameters at any dose
are therefore the linear interpolation (or extrapolation) between the awake and anesthetized
files. This is checked: each parameter that differs between the two files must be 2.5 times
its awake value, or the ASC2 weight, which falls from 1.5 to 0.
"""
function parameters_at_dose(trial, P)
    p_aw, p_an = parameters(trial, :awake), parameters(trial, :anesthetized)
    for i in findall(p_aw .!= p_an)
        name = String(MODEL.param_names[i])
        ok = isapprox(p_an[i], P_ANESTHETIC * p_aw[i]; rtol=1e-9) ||
             (occursin("ASC2", name) && isapprox(p_aw[i], 1.5) && iszero(p_an[i]))
        ok || error("parameter $name is not linear in the dose as expected: ",
                    "awake $(p_aw[i]), anesthetized $(p_an[i])")
    end
    p_aw .+ (P - 1) / (P_ANESTHETIC - 1) .* (p_an .- p_aw)
end

# ── Simulated MUA ────────────────────────────────────────────────────────────────────────────
#
# As in the manuscript (Methods, Simulated multi-unit activity), the MUA of a region is the mean
# synaptic conductance generated by its neurons:
#   posterior: AMPA synapses of the excitatory neurons of layers 2/3, 4, 5 and 6 (modules A and
#              B), and GABA-A synapses of the interneurons of layer 4;
#   anterior:  AMPA synapses of the excitatory neurons of the anterior layer 2/3.
# Each synapse is a state of the neuron it belongs to. With the conductance synapse model
# (ConductanceRule) its conductance is the state `glu_ampa₊G` / `gaba_a₊G`; with the
# transmitter-receptor model (Kinetic2StateRule) it is `G_syn * O`, the maximal conductance times
# the open fraction `glu_ampa_rec₊O` / `gaba_a_rec₊O`.

const REGION_LAYERS = (
    posterior = (ampa = ("Layer_2_3_A", "Layer_2_3_B", "Layer_4_A", "Layer_4_B",
                         "Layer_5_A", "Layer_5_B", "Layer_6_A", "Layer_6_B"),
                 gaba = ("Layer_4_A", "Layer_4_B")),
    anterior  = (ampa = ("Layer_2_3_ac",), gaba = ()),
)

in_layers(name, layers) = any(l -> startswith(name, "g₊" * l * "₊"), layers)

"""
    mua_synapses(region)

The indices of the synaptic states that make up the MUA of `region` (`:posterior` or
`:anterior`), and for each the index of the parameter it is multiplied by (`nothing` for the
conductance synapse model, whose state already is a conductance).
"""
function mua_synapses(region)
    layers = REGION_LAYERS[region]
    names = String.(MODEL.state_names)
    pindex = Dict(String(n) => i for (i, n) in enumerate(MODEL.param_names))
    kinetic = any(endswith("₊glu_ampa_rec₊O"), names)
    ampa, gaba = kinetic ? ("₊glu_ampa_rec₊O", "₊gaba_a_rec₊O") : ("₊glu_ampa₊G", "₊gaba_a₊G")
    idx = [i for (i, n) in enumerate(names)
           if (endswith(n, ampa) && in_layers(n, layers.ampa)) ||
              (endswith(n, gaba) && in_layers(n, layers.gaba))]
    isempty(idx) && error("no synaptic states found for the $region MUA")
    gsyn = kinetic ? [pindex[chop(names[i]) * "G_syn"] for i in idx] :
                     fill(nothing, length(idx))
    (; idx, gsyn, kinetic)
end

"""
    simulate(p; regions=(:posterior, :anterior), saveat=0.1)

Solve one trial with parameter vector `p` and return `(; t, mua)`, with `mua.<region>` the
simulated MUA of each region over the saved times `t` [ms].
"""
function simulate(p; regions=(:posterior, :anterior), saveat=0.1)
    syn = NamedTuple{regions}(map(mua_synapses, regions))
    save_idxs = unique(reduce(vcat, [s.idx for s in syn]))
    sol = solve(MODEL.problem(; p), Vern7(); saveat, save_idxs)
    sol.retcode == ReturnCode.Success || @warn "solver returned $(sol.retcode)"
    U = reduce(hcat, sol.u)                       # saved states × time
    col = Dict(j => k for (k, j) in enumerate(save_idxs))
    mua = NamedTuple{regions}(map(regions) do r
        s = syn[r]
        G = [U[col[i], :] .* (g === nothing ? 1.0 : p[g]) for (i, g) in zip(s.idx, s.gsyn)]
        vec(mean(reduce(hcat, G), dims=2))
    end)
    (; t = sol.t, mua)
end

"Write columns of equal length, with a header, to a CSV file."
function write_csv(path, header, columns)
    mkpath(dirname(path))
    open(path, "w") do io
        println(io, join(header, ','))
        for k in eachindex(first(columns))
            println(io, join((c[k] for c in columns), ','))
        end
    end
end
